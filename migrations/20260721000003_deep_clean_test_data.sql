-- =============================================================================
-- 深度清理测试数据（测试题目 + 测试用户）
-- =============================================================================
-- 纯净标准 SQL，无 psql 专属语法，sqlx migrate!() 可直接执行。
-- 幂等设计：DELETE 语句天然幂等，重复执行不会报错。
--
-- 清理范围：
--   1. 测试题目：questions.stem 含"测试"或"test"（不区分大小写）
--   2. 测试用户：users.username 含"test"（不区分大小写），但保留 'visualtest'
--      仅删除没有关联题目的测试用户，避免破坏外键约束
--
-- 安全特性：
--   1. 全程包裹在 BEGIN/COMMIT 事务中，出错即 ROLLBACK
--   2. 先删题目，再删用户，避免外键约束冲突
--   3. 测试用户删除前检查是否还有关联题目，有则跳过
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- Step 1: 删除测试题目（stem 包含"测试"或"test"）
--   先删题目，避免后续删除测试用户时遇到外键约束
-- -----------------------------------------------------------------------------

DELETE FROM questions
WHERE stem ILIKE '%测试%'
   OR stem ILIKE '%test%';

-- -----------------------------------------------------------------------------
-- Step 2: 删除测试用户（username 含"test"，但保留 'visualtest'）
--   仅删除没有关联题目的用户，避免破坏外键约束
--   如果测试用户仍有题目，说明题目不是测试题目，保留用户
-- -----------------------------------------------------------------------------

DELETE FROM users
WHERE username ILIKE '%test%'
  AND username != 'visualtest'
  AND id NOT IN (
      SELECT DISTINCT creator_id FROM questions WHERE creator_id IS NOT NULL
  );

COMMIT;
